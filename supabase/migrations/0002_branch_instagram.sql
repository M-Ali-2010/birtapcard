-- Instagram филиала.
--
-- После того как гость оставил отзыв в Google и вернулся в браузер,
-- показываем ему панель «Подпишитесь на нас в Instagram». Ссылка своя
-- у каждого филиала — сеть может вести разные аккаунты по точкам.
--
-- Колонка необязательная: если она пустая, поведение прежнее —
-- сканирование сразу уводит на Google без всякой панели.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.branches
  add column if not exists instagram_url text;

comment on column public.branches.instagram_url is
  'Ссылка на Instagram заведения. Пусто — панель подписки не показывается.';
